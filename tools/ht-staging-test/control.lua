-- B-I9: only the area around spawn is generated. One territory with a placed brain is claimed (brain killed);
-- its staging must be a touching neighbour, whose base gets generated on demand.
local out = {}
local function p(...) out[#out + 1] = string.format(...) end
local target
local function touching(a, b)
  local own = {}
  for _, c in pairs(a.get_chunks()) do own[c.x .. "," .. c.y] = true end
  for _, c in pairs(b.get_chunks()) do
    for dx = -1, 1 do for dy = -1, 1 do if own[(c.x + dx) .. "," .. (c.y + dy)] then return true end end end
  end
  return false
end
script.on_event(defines.events.on_tick, function(e)
  local s = game.surfaces.nauvis
  if e.tick == 2 then
    s.request_to_generate_chunks({0, 0}, 10)
    s.force_generate_chunk_requests()
  elseif e.tick == 10 then
    local gen = 0 for c in s.get_chunks() do if s.is_chunk_generated(c) then gen = gen + 1 end end
    p("generated chunks: %d; spawners on the map: %d", gen, s.count_entities_filtered{type = "unit-spawner"})
    for _, u in pairs(s.get_segmented_units()) do
      local h = u.segments[1].position
      target = u.territory u.die() break
    end
  elseif e.tick == 12 then
    local id = script.register_on_object_destroyed(target)
    local before = {} for c in s.get_chunks() do if s.is_chunk_generated(c) then before[c.x .. "," .. c.y] = true end end
    local r = remote.call("hostile-territory-debug", "staging_for", id)
    if not r then p("target %d: no staging", id) else
      local st
      for _, t in pairs(s.get_territories()) do if script.register_on_object_destroyed(t) == r.id then st = t end end
      local ck = math.floor(r.x / 32) .. "," .. math.floor(r.y / 32)
      local new = 0 for c in s.get_chunks() do if s.is_chunk_generated(c) and not before[c.x .. "," .. c.y] then new = new + 1 end end
      p("target %d (claimed): staging territory %d, nest at %.1f,%.1f; touches target: %s; nest chunk generated before the call: %s; chunks generated by the call: %d",
        id, r.id, r.x, r.y, tostring(st and touching(target, st)), tostring(before[ck] == true), new)
    end
    p("%s", remote.call("hostile-territory-debug", "brains"))
    helpers.write_file("staging-result.txt", table.concat(out, "\n"))
  end
end)
